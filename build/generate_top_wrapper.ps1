# =============================================================
# generate_top_wrapper.ps1
# Generates autogen_top_wrapper.sv with current build settings.
# Called by build_win_v2.ps1 before running gw_sh.exe
# =============================================================
#
# Stage 1B: Added 18 memory bus internal wires and wired them to top_inst,
# user_inst (user branch), and tied idle in board_demonstration_inst (demo branch).
# =============================================================

param (
    [string]$BuildArtifactsDirectory,   # where to save the file
    [string]$TopWrapperFilename,        # filename e.g. "autogen_top_wrapper.sv"
    [int]$ClockFrequencyMhz = 51,       # system clock frequency
    [int]$UartBaud          = 115200,   # uart baud rate
    [int]$PushbuttonReset   = 1,        # pushbutton reset enabled
    [int]$BoardDemonstration = 0        # 0 = user.sv, 1 = board_demonstration.sv
)


# ---- VALIDATE REQUIRED ARGUMENTS ----
if (-not $BuildArtifactsDirectory) {
    Write-Host "ERROR: -BuildArtifactsDirectory is required."
    Write-Host "Usage: .\generate_top_wrapper.ps1 -BuildArtifactsDirectory <path> -TopWrapperFilename <filename>"
    exit 1
}
if (-not $TopWrapperFilename) {
    Write-Host "ERROR: -TopWrapperFilename is required."
    Write-Host "Usage: .\generate_top_wrapper.ps1 -BuildArtifactsDirectory <path> -TopWrapperFilename <filename>"
    exit 1
}


# ---- GET GIT INFO ----
$gitShortRev     = git rev-parse --short HEAD
$gitLocalChanges = git diff-index HEAD
$gitDirty        = if ($gitLocalChanges) { "-dirty" } else { "" }
$timeStr         = Get-Date -Format "yyyy-MM-dd HH:mm:ss"
$buildVersion    = "FW: ${gitShortRev}${gitDirty}|${timeStr}"
$buildVersionLen = $buildVersion.Length

Write-Host "  Git commit  : $gitShortRev$gitDirty"
Write-Host "  Build time  : $timeStr"
Write-Host "  Version str : $buildVersion"

# ---- GENERATE FILE CONTENT ----
# note: backtick in systemverilog (e.g. `timescale) must be written
# as double backtick (``) inside a PowerShell here-string
$content = @"
//
//                          !!! WARNING !!!
//
//     This file is autogenerated - modifications will not persist !
//
//

// -------------------------------------------------------------------------
// COPYRIGHT © 2025, BRISBANE SILICON, PTY LTD.
//
// THE SOURCE CODE CONTAINED HEREIN IS PROVIDED ON AN "AS IS" BASIS.
// BRISBANE SILICON, PTY LTD. DISCLAIMS ANY AND ALL WARRANTIES,
// WHETHER EXPRESS, IMPLIED, OR STATUTORY, INCLUDING ANY IMPLIED
// WARRANTIES OF MERCHANTABILITY OR OF FITNESS FOR A PARTICULAR PURPOSE.
// IN NO EVENT SHALL BRISBANE SILICON, PTY LTD. BE LIABLE FOR ANY
// INCIDENTAL, PUNITIVE, OR CONSEQUENTIAL DAMAGES OF ANY KIND WHATSOEVER
// ARISING FROM THE USE OF THIS SOURCE CODE.
//
// THIS DISCLAIMER OF WARRANTY EXTENDS TO THE USER OF THIS SOURCE CODE
// AND USER'S CUSTOMERS, EMPLOYEES, AGENTS, TRANSFEREES, SUCCESSORS,
// AND ASSIGNS.
//
// THIS IS NOT A GRANT OF PATENT RIGHTS
//
// -------------------------------------------------------------------------
// DESCRIPTION : Auto-generated top wrapper.
//
// -------------------------------------------------------------------------
// SPECIFICATION :
//
// -------------------------------------------------------------------------

``timescale 1ns/1ps

import util::*;

module autogen_top_wrapper #(
    parameter reg   [(8*VERSION_CHARS)-1:0] VERSION                 = "$buildVersion",
    parameter int                           VERSION_LEN             = $buildVersionLen,

    parameter int                           CLK_FREQUENCY_MHZ       = $ClockFrequencyMhz,
    parameter int                           UART_BAUD               = $UartBaud,
    parameter int                           PUSHBUTTON0_AS_RESET    = $PushbuttonReset,
    parameter int                           BOARD_DEMONSTRATION     = $BoardDemonstration

) (
    input                               pad_clk_27Mhz,

    input   [1:0]                       pad_user_buttons_n,
    inout   [5:0]                       pad_leds_n,
    input                               pad_ser_rx,
    output                              pad_ser_tx,
    inout   [32:1]                      pad_io,

    output                              pad_flash_clk,
    output                              pad_flash_csb,
    inout                               pad_flash_mosi,
    inout                               pad_flash_miso,

    // NOTE: these ports are needed,
    // or the PSRAM IP will not
    // compile...
    output  [CS_WIDTH-1:0]              O_psram_ck,
    output  [CS_WIDTH-1:0]              O_psram_ck_n,
    inout   [CS_WIDTH-1:0]              IO_psram_rwds,
    inout   [DQ_WIDTH-1:0]              IO_psram_dq,
    output  [CS_WIDTH-1:0]              O_psram_reset_n,
    output  [CS_WIDTH-1:0]              O_psram_cs_n
);
localparam VERSION_CHARS    = 63;
localparam DQ_WIDTH         = 16;
localparam CS_WIDTH         = 2;


    // ----------------------------------------------
    //  Internal signals
    // ----------------------------------------------

    reg [5:0]                                           i_top_leds;
    reg [5:0]                                           i_user_leds;

    reg                                                 i_sysclk;
    reg                                                 i_sysclk_resetn  = 1'b0;

    reg                                                 i_microsecond_tick;
    reg                                                 i_millisecond_tick;
    reg                                                 i_second_tick;

    reg                                                 i_uart_tx_valid;
    reg                                                 i_uart_tx_ready;
    reg                         [7:0]                   i_uart_tx_data;
    reg                                                 i_uart_rx_valid;
    reg                                                 i_uart_rx_ready;
    reg                         [7:0]                   i_uart_rx_data;

    reg                         [31:0]                  i_ram_addr;
    reg                         [31:0]                  i_ram_wdata;
    reg                         [3:0]                   i_ram_wstrb;
    reg                         [31:0]                  i_ram_rdata;
    reg                                                 i_ram_valid;
    reg                                                 i_ram_ready;

    reg                         [31:0]                  i_flash_cfg_addr;
    reg                         [31:0]                  i_flash_cfg_wdata;
    reg                         [3:0]                   i_flash_cfg_wstrb;
    reg                         [31:0]                  i_flash_cfg_rdata;
    reg                                                 i_flash_cfg_valid;
    reg                                                 i_flash_cfg_ready;

    reg                         [31:0]                  i_flash_xip_addr;
    reg                         [31:0]                  i_flash_xip_wdata;
    reg                         [3:0]                   i_flash_xip_wstrb;
    reg                         [31:0]                  i_flash_xip_rdata;
    reg                                                 i_flash_xip_valid;
    reg                                                 i_flash_xip_ready;


    // ----------------------------------------------
    //  Implementation
    // ----------------------------------------------

    top #(
        .VERSION                    (VERSION),
        .CLK_FREQUENCY_MHZ          (CLK_FREQUENCY_MHZ),
        .UART_BAUD                  (UART_BAUD),
        .PUSHBUTTON0_AS_RESET       (PUSHBUTTON0_AS_RESET)
    ) top_inst (

        // ---------------- pads ----------------

        .clk_27Mhz                  (pad_clk_27Mhz),

        .user_pushbutton0_n         (pad_user_buttons_n[0]),
        .user_pushbutton1_n         (pad_user_buttons_n[1]),
        .uart_rx                    (pad_ser_rx),
        .uart_tx                    (pad_ser_tx),
        .leds                       (i_top_leds),

        .flash_clk                  (pad_flash_clk),
        .flash_csb                  (pad_flash_csb),
        .flash_mosi                 (pad_flash_mosi),
        .flash_miso                 (pad_flash_miso),

        .psram_ck                   (O_psram_ck),
        .psram_ck_n                 (O_psram_ck_n),
        .psram_rwds                 (IO_psram_rwds),
        .psram_dq                   (IO_psram_dq),
        .psram_reset_n              (O_psram_reset_n),
        .psram_cs_n                 (O_psram_cs_n),


        // -------------- fabric --------------

        .sysclk                     (i_sysclk),
        .sysclk_resetn              (i_sysclk_resetn),

        .microsecond_tick           (i_microsecond_tick),
        .millisecond_tick           (i_millisecond_tick),
        .second_tick                (i_second_tick),

        .uart_tx_valid              (i_uart_tx_valid),
        .uart_tx_ready              (i_uart_tx_ready),
        .uart_tx_data               (i_uart_tx_data),
        .uart_rx_valid              (i_uart_rx_valid),
        .uart_rx_ready              (i_uart_rx_ready),
        .uart_rx_data               (i_uart_rx_data),

        // -------------- memory fabric --------------

        .ram_addr                   (i_ram_addr),
        .ram_wdata                  (i_ram_wdata),
        .ram_wstrb                  (i_ram_wstrb),
        .ram_rdata                  (i_ram_rdata),
        .ram_valid                  (i_ram_valid),
        .ram_ready                  (i_ram_ready),

        .flash_cfg_addr             (i_flash_cfg_addr),
        .flash_cfg_wdata            (i_flash_cfg_wdata),
        .flash_cfg_wstrb            (i_flash_cfg_wstrb),
        .flash_cfg_rdata            (i_flash_cfg_rdata),
        .flash_cfg_valid            (i_flash_cfg_valid),
        .flash_cfg_ready            (i_flash_cfg_ready),

        .flash_xip_addr             (i_flash_xip_addr),
        .flash_xip_wdata            (i_flash_xip_wdata),
        .flash_xip_wstrb            (i_flash_xip_wstrb),
        .flash_xip_rdata            (i_flash_xip_rdata),
        .flash_xip_valid            (i_flash_xip_valid),
        .flash_xip_ready            (i_flash_xip_ready)
    );


    generate
        if(BOARD_DEMONSTRATION) begin

            // ----------------------------------------------
            //  Board Demonstration
            // ----------------------------------------------

            board_demonstration #(
                .VERSION            (VERSION),
                .VERSION_LEN        (VERSION_LEN)
            ) board_demonstration_inst (
                .sysclk             (i_sysclk),
                .sysclk_resetn      (i_sysclk_resetn),

                .microsecond_tick   (i_microsecond_tick),
                .millisecond_tick   (i_millisecond_tick),
                .second_tick        (i_second_tick),

                .io                 (pad_io),

                .uart_tx_valid      (i_uart_tx_valid),
                .uart_tx_ready      (i_uart_tx_ready),
                .uart_tx_data       (i_uart_tx_data),
                .uart_rx_valid      (i_uart_rx_valid),
                .uart_rx_ready      (i_uart_rx_ready),
                .uart_rx_data       (i_uart_rx_data),

                .ram_addr           (i_ram_addr),
                .ram_wdata          (i_ram_wdata),
                .ram_wstrb          (i_ram_wstrb),
                .ram_rdata          (i_ram_rdata),
                .ram_valid          (i_ram_valid),
                .ram_ready          (i_ram_ready),

                .flash_cfg_addr     (i_flash_cfg_addr),
                .flash_cfg_wdata    (i_flash_cfg_wdata),
                .flash_cfg_wstrb    (i_flash_cfg_wstrb),
                .flash_cfg_rdata    (i_flash_cfg_rdata),
                .flash_cfg_valid    (i_flash_cfg_valid),
                .flash_cfg_ready    (i_flash_cfg_ready),

                .flash_xip_addr     (i_flash_xip_addr),
                .flash_xip_wdata    (i_flash_xip_wdata),
                .flash_xip_wstrb    (i_flash_xip_wstrb),
                .flash_xip_rdata    (i_flash_xip_rdata),
                .flash_xip_valid    (i_flash_xip_valid),
                .flash_xip_ready    (i_flash_xip_ready)
            );

            assign pad_leds_n = ~i_top_leds;
                // NOTE:
                //          led[4]: pin activity
                //          led[3]: flash activity
                //          led[2]: hyperram activity
                //          led[1]: uart activity
                //          led[0]: heartbeat

        end else begin

            // ----------------------------------------------
            //  User
            // ----------------------------------------------

            user user_inst (
                .sysclk             (i_sysclk),
                .sysclk_resetn      (i_sysclk_resetn),

                .microsecond_tick   (i_microsecond_tick),
                .millisecond_tick   (i_millisecond_tick),
                .second_tick        (i_second_tick),

                .leds               (i_user_leds),

                .io                 (pad_io),

                .uart_tx_valid      (i_uart_tx_valid),
                .uart_tx_ready      (i_uart_tx_ready),
                .uart_tx_data       (i_uart_tx_data),
                .uart_rx_valid      (i_uart_rx_valid),
                .uart_rx_ready      (i_uart_rx_ready),
                .uart_rx_data       (i_uart_rx_data),

                .ram_addr           (i_ram_addr),
                .ram_wdata          (i_ram_wdata),
                .ram_wstrb          (i_ram_wstrb),
                .ram_rdata          (i_ram_rdata),
                .ram_valid          (i_ram_valid),
                .ram_ready          (i_ram_ready),

                .flash_cfg_addr     (i_flash_cfg_addr),
                .flash_cfg_wdata    (i_flash_cfg_wdata),
                .flash_cfg_wstrb    (i_flash_cfg_wstrb),
                .flash_cfg_rdata    (i_flash_cfg_rdata),
                .flash_cfg_valid    (i_flash_cfg_valid),
                .flash_cfg_ready    (i_flash_cfg_ready),

                .flash_xip_addr     (i_flash_xip_addr),
                .flash_xip_wdata    (i_flash_xip_wdata),
                .flash_xip_wstrb    (i_flash_xip_wstrb),
                .flash_xip_rdata    (i_flash_xip_rdata),
                .flash_xip_valid    (i_flash_xip_valid),
                .flash_xip_ready    (i_flash_xip_ready)
            );

            assign pad_leds_n = ~i_user_leds;
        end
    endgenerate

endmodule
"@

# ---- WRITE TO FILE ----
$BuildArtifactsDirectory = $ExecutionContext.SessionState.Path.GetUnresolvedProviderPathFromPSPath($BuildArtifactsDirectory)
$outputPath = Join-Path $BuildArtifactsDirectory $TopWrapperFilename

# create directory if it doesn't exist
if (-not (Test-Path $BuildArtifactsDirectory)) {
    Write-Host "  Creating artifacts directory: $BuildArtifactsDirectory"
    New-Item -ItemType Directory -Path $BuildArtifactsDirectory -Force | Out-Null
}

# write file — UTF-8 without BOM to match Linux output
[System.IO.File]::WriteAllText($outputPath, $content, [System.Text.UTF8Encoding]::new($false))

Write-Host "  Generated   : $outputPath"
